    private void btnIgualActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIgualActionPerformed
        // TODO add your handling code here:
     if (operacao.equals("")) {
        return; 
    }

    valor2 = Double.parseDouble(lblResultado.getText());

    if (operacao.equals("divisao") && valor2 == 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Impossível dividir por zero!");
        lblResultado.setText("0");
        lblValorAnterior.setText("");
        valor1 = 0;
        valor2 = 0;
        operacao = "";
        return; 
    }

    if (operacao.equals("soma")) {
        valor1 = valor1 + valor2;
    } else if (operacao.equals("subtracao")) {
        valor1 = valor1 - valor2;
    } else if (operacao.equals("multiplicacao")) {
        valor1 = valor1 * valor2;
    } else if (operacao.equals("divisao")) {
        valor1 = valor1 / valor2;
    }

    lblResultado.setText(String.valueOf(valor1));
    lblValorAnterior.setText("");
    operacao = "";
    }//GEN-LAST:event_btnIgualActionPerformed

