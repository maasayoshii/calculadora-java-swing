    private void btnMaisActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMaisActionPerformed
        // TODO add your handling code here:
        double valorAtual = Double.parseDouble(lblResultado.getText());
    
    if (!operacao.equals("")) {
        if (operacao.equals("soma")) { valor1 = valor1 + valorAtual; }
        else if (operacao.equals("subtracao")) { valor1 = valor1 - valorAtual; }
        else if (operacao.equals("multiplicacao")) { valor1 = valor1 * valorAtual; }
        else if (operacao.equals("divisao")) { valor1 = valor1 / valorAtual; }
    } else {
        valor1 = valorAtual;
    }
    
    operacao = "soma";
    lblValorAnterior.setText(valor1 + " + ");
    lblResultado.setText("0");
    }//GEN-LAST:event_btnMaisActionPerformed

